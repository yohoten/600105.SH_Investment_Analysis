def t_val():
    v = d["val"].dropna(subset=["PE_TTM"])
    v = v[v["日期"] >= "2017-01-01"]
    cur = d["val"].iloc[-1]
    rows = []
    for lab, col, s in [("PE(TTM，倍)", "PE_TTM", v["PE_TTM"]),
                        ("PB(MRQ，倍)", "PB", d["val"].dropna(subset=["PB"])["PB"]),
                        ("PS(TTM，倍)", "PS_TTM", d["val"].dropna(subset=["PS_TTM"])["PS_TTM"])]:
        pct = (s <= cur[col]).mean() * 100
        rows.append((lab, round(cur[col], 2), round(s.median(), 2), f"{pct:.1f}%"))
    return pd.DataFrame(rows, columns=["估值指标", "当前值", "2017年以来中位数", "当前历史分位"])


