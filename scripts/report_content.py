def t_bridge():
    p = d["panel"].copy()
    p["期末"] = pd.to_datetime(p["REPORT_DATE"])
    y = p[p["报告期"] == "2025年报"].iloc[0]
    rev = y["营业收入"] / 1e8
    cost = y["营业成本"] / 1e8
    gp = rev - cost
    exp = sum(y[c] for c in ["销售费用", "管理费用", "研发费用", "财务费用"]) / 1e8
    inv = y["投资收益"] / 1e8
    oth = y["其他收益"] / 1e8
    imp = (y["资产减值损失"] + y["信用减值损失"]) / 1e8
    op = y["营业利润"] / 1e8
    rows = [
        ("营业收入", rev, "合并口径，同比 +28.6%"),
        ("减：营业成本", -cost, f"毛利率 {gp / rev * 100:.2f}%"),
        ("＝毛利", gp, "十年次低，仅高于 2020 年"),
        ("减：期间费用", -exp, f"期间费用率 {exp / rev * 100:.2f}%"),
        ("＝主业经营利润", gp - exp, "主业实际亏损"),
        ("加：投资收益", inv, "含联营企业东昌投资权益法确认 2.74 亿元"),
        ("加：其他收益", oth, "政府补助等"),
        ("加：减值损失", imp, "资产减值 −0.38、信用减值 −0.18"),
        ("＝营业利润", op, ""),
        ("归母净利润", ra.loc[2025, "归母净利润(亿元)"], "少数股东损益占比很小"),
        ("扣非归母净利润", ra.loc[2025, "扣非归母净利润(亿元)"], "剔除非经常性损益后"),
    ]
    return pd.DataFrame([(a, round(b, 2), c) for a, b, c in rows],
                        columns=["项目", "金额(亿元)", "说明"])


